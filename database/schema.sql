-- RouteWise PostgreSQL schema. Run while connected to the routewise database.
CREATE TABLE IF NOT EXISTS users (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','DEPOT_STAFF','COMMUTER')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS stops (
  stop_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stop_code VARCHAR(30) NOT NULL UNIQUE,
  stop_name VARCHAR(120) NOT NULL,
  area VARCHAR(120) NOT NULL,
  latitude NUMERIC(9,6) CHECK (latitude BETWEEN -90 AND 90),
  longitude NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180),
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS routes (
  route_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_code VARCHAR(30) NOT NULL UNIQUE,
  route_name VARCHAR(160) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS route_stops (
  route_id BIGINT NOT NULL REFERENCES routes(route_id) ON DELETE CASCADE,
  stop_id BIGINT NOT NULL REFERENCES stops(stop_id) ON DELETE RESTRICT,
  stop_sequence INTEGER NOT NULL CHECK (stop_sequence > 0),
  PRIMARY KEY (route_id, stop_sequence),
  UNIQUE (route_id, stop_id)
);
CREATE TABLE IF NOT EXISTS buses (
  bus_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration_no VARCHAR(30) NOT NULL UNIQUE,
  capacity INTEGER NOT NULL CHECK (capacity > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','MAINTENANCE','RETIRED'))
);
CREATE TABLE IF NOT EXISTS trips (
  trip_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_id BIGINT NOT NULL REFERENCES routes(route_id) ON DELETE RESTRICT,
  bus_id BIGINT NOT NULL REFERENCES buses(bus_id) ON DELETE RESTRICT,
  service_date DATE NOT NULL,
  planned_start TIME NOT NULL,
  trip_status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED' CHECK (trip_status IN ('SCHEDULED','COMPLETED','CANCELLED'))
);
CREATE TABLE IF NOT EXISTS trip_stop_times (
  trip_id BIGINT NOT NULL REFERENCES trips(trip_id) ON DELETE CASCADE,
  stop_sequence INTEGER NOT NULL CHECK (stop_sequence > 0),
  stop_id BIGINT NOT NULL REFERENCES stops(stop_id) ON DELETE RESTRICT,
  scheduled_arrival TIMESTAMPTZ NOT NULL,
  actual_arrival TIMESTAMPTZ,
  PRIMARY KEY (trip_id, stop_sequence),
  UNIQUE (trip_id, stop_id)
);
CREATE TABLE IF NOT EXISTS delay_reports (
  report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id BIGINT NOT NULL REFERENCES trips(trip_id) ON DELETE CASCADE,
  stop_id BIGINT NOT NULL REFERENCES stops(stop_id) ON DELETE RESTRICT,
  reported_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  delay_minutes INTEGER NOT NULL CHECK (delay_minutes BETWEEN 0 AND 240),
  cause VARCHAR(200) NOT NULL DEFAULT 'Unknown',
  observed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (length(trim(cause)) > 0)
);
CREATE TABLE IF NOT EXISTS delay_alerts (
  alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL UNIQUE REFERENCES delay_reports(report_id) ON DELETE CASCADE,
  alert_message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  resolved BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS complaints (
  complaint_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submitted_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  route_id BIGINT REFERENCES routes(route_id) ON DELETE SET NULL,
  stop_id BIGINT REFERENCES stops(stop_id) ON DELETE SET NULL,
  description TEXT NOT NULL CHECK (length(trim(description)) > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','IN_REVIEW','RESOLVED','REJECTED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_route_stops_stop_id ON route_stops(stop_id);
CREATE INDEX IF NOT EXISTS idx_trips_route_date ON trips(route_id, service_date);
CREATE INDEX IF NOT EXISTS idx_trip_stop_times_stop ON trip_stop_times(stop_id);
CREATE INDEX IF NOT EXISTS idx_delay_reports_trip_time ON delay_reports(trip_id, observed_at DESC);
CREATE INDEX IF NOT EXISTS idx_delay_reports_stop ON delay_reports(stop_id);
CREATE INDEX IF NOT EXISTS idx_complaints_status_created ON complaints(status, created_at DESC);
